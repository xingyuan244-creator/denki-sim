if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }

$quiet = 4
$n = $rows.Count
$side = $n + $quiet * 2

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="UTF-8"?>')
[void]$sb.AppendLine("<svg xmlns=`"http://www.w3.org/2000/svg`" viewBox=`"0 0 $side $side`" shape-rendering=`"crispEdges`" role=`"img`" aria-label=`"$url`">")
[void]$sb.AppendLine("  <title>$url</title>")
[void]$sb.AppendLine("  <rect width=`"$side`" height=`"$side`" fill=`"#ffffff`"/>")
[void]$sb.AppendLine('  <g fill="#000000">')
for ($r = 0; $r -lt $n; $r++) {
  $line = $rows[$r]
  $c = 0
  while ($c -lt $n) {
    if ($line[$c] -eq '1') {
      $start = $c
      while ($c -lt $n -and $line[$c] -eq '1') { $c++ }
      $w = $c - $start
      [void]$sb.AppendLine("    <rect x=`"$($start+$quiet)`" y=`"$($r+$quiet)`" width=`"$w`" height=`"1`"/>")
    } else { $c++ }
  }
}
[void]$sb.AppendLine('  </g>')
[void]$sb.AppendLine('</svg>')

$path = Join-Path $OutDir "$name.svg"
[System.IO.File]::WriteAllText($path, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
